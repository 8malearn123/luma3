import { loomApi, metricDisplay, type PlanDraft } from '@/loom';
import { withTenant } from '../db/client';
import type { TenantAccess } from '../tenancy/access';
import type { PlanContent } from '@/shared/schemas/marketing';
import { toPlanContent } from './planner-port';
import { examplePlan } from '../domains/marketing/rules';

/**
 * Owner-facing plan views (LUMA-AUDIT-023/024/038/039).
 *  - Loom-generated versions are re-rendered from their bilingual draft in the
 *    reader's locale (plan titles and items are no longer Arabic-only in the
 *    English interface). Stored versions are never modified.
 *  - Baseline and metric rows carry a readable label and their unit so the UI
 *    formats money from minor units instead of printing 1676505.
 *  - Each version carries an accurate provenance: generated by the planner
 *    (rules or AI), added from an approved opportunity, a proposed revision,
 *    or edited by a person.
 */
export type Provenance = 'ai' | 'rules' | 'example' | 'user_edit' | 'user_created' | 'opportunity_added' | 'revision' | 'regenerated';

const pick = (t: { ar: string; en: string } | null | undefined, l: 'ar' | 'en') => (t ? (l === 'ar' ? t.ar || t.en : t.en || t.ar) : '');

export function provenanceOf(v: { source: string; change_note: string | null; version: number }): Provenance {
  const note = v.change_note ?? '';
  if (note.startsWith('loom:')) return 'opportunity_added';
  if (note.startsWith('revision:')) return 'revision';
  if (v.source === 'ai' || v.source === 'rules') return note === 'regenerated' ? 'regenerated' : v.source;
  if (v.source === 'example') return 'example';
  return v.version === 1 ? 'user_created' : 'user_edit';
}

type Names = Awaited<ReturnType<typeof loomApi.subjectNames>>;

/** Display labels/units per baseline and metric row (index-aligned; content itself stays schema-valid for editing). */
function displayOf(c: PlanContent, names: Names, locale: 'ar' | 'en') {
  return {
    baseline: c.baseline.map((b) => metricDisplay(b.metric_key, names, locale, b.label)),
    metrics: c.metrics.map((m) => metricDisplay(m.key, names, locale, m.label)),
  };
}

/** Loom drafts (bilingual) of the given versions, by version id. */
async function draftsOf(tenantId: string, versionIds: string[]) {
  if (!versionIds.length) return new Map<string, PlanDraft>();
  const rows = await withTenant(tenantId, (trx) => trx.selectFrom('loom.planner_runs').select(['plan_version_id', 'result'])
    .where('business_id', '=', tenantId).where('plan_version_id', 'in', versionIds).execute());
  const out = new Map<string, PlanDraft>();
  for (const r of rows) {
    const d = (r.result as { draft?: PlanDraft } | null)?.draft;
    if (r.plan_version_id && d?.title) out.set(r.plan_version_id, d);
  }
  return out;
}

/** Localized titles of Loom-generated plans (from the plan's first planner draft). */
export async function localizedPlanTitles(tenantId: string, planIds: string[], locale: 'ar' | 'en') {
  const out = new Map<string, string>();
  if (!planIds.length) return out;
  const rows = await withTenant(tenantId, (trx) => trx.selectFrom('loom.planner_runs').select(['plan_id', 'result', 'created_at'])
    .where('business_id', '=', tenantId).where('plan_id', 'in', planIds).where('kind', '!=', 'revision').where('status', '=', 'succeeded').orderBy('created_at').execute());
  for (const r of rows) {
    const title = (r.result as { draft?: { title?: { ar: string; en: string } } } | null)?.draft?.title;
    if (r.plan_id && title && !out.has(r.plan_id)) out.set(r.plan_id, pick(title, locale));
  }
  return out;
}

type ExampleRef = { is_example?: boolean; kind?: string; period_start?: string; period_end?: string };
/** Example plans are fixed bilingual text: render them in the reader's locale. */
const exampleFor = (p: ExampleRef, locale: 'ar' | 'en') => (p.is_example && p.period_start && p.period_end ? examplePlan(locale, p.kind === 'weekly' ? 'weekly' : 'monthly', p.period_start, p.period_end) : null);

export async function localizePlanList<T extends { id: string; title: string } & ExampleRef>(access: TenantAccess, rows: T[], locale: 'ar' | 'en'): Promise<T[]> {
  const titles = await localizedPlanTitles(access.tenantId, rows.map((r) => r.id), locale);
  return rows.map((r) => ({ ...r, title: titles.get(r.id) || exampleFor(r, locale)?.title || r.title }));
}

export async function localizePlan<P extends { id: string; title: string; versions: Array<{ id: string; version: number; source: string; change_note: string | null; content: unknown }>; parent?: { id: string; title: string } | null }>(access: TenantAccess, plan: P, locale: 'ar' | 'en') {
  const [drafts, names, titles] = await Promise.all([
    draftsOf(access.tenantId, plan.versions.map((v) => v.id)),
    loomApi.subjectNames(access.tenantId),
    localizedPlanTitles(access.tenantId, [plan.id, ...(plan.parent ? [plan.parent.id] : [])], locale),
  ]);
  const ex = exampleFor(plan as ExampleRef, locale);
  return {
    ...plan,
    title: titles.get(plan.id) || ex?.title || plan.title,
    parent: plan.parent ? { ...plan.parent, title: titles.get(plan.parent.id) || plan.parent.title } : null,
    versions: plan.versions.map((v) => {
      const d = drafts.get(v.id);
      const content = d ? toPlanContent(d, locale) : v.source === 'example' && ex ? ex.content : (v.content as PlanContent);
      return { ...v, content, display: displayOf(content, names, locale), provenance: provenanceOf(v), localized_from_draft: !!d };
    }),
  };
}

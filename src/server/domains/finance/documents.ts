import { escapeHtml as e } from '../../infra/pdf';
import { formatDateTime, formatMoney } from '@/shared/format';

type Invoice = Awaited<ReturnType<typeof import('./service').getInvoice>>;

/** Self-contained RTL document for receipts/invoices (print view and PDF share it). */
export function invoiceHtml(inv: Invoice, locale: 'ar' | 'en' = 'ar') {
  const seller = inv.seller_snapshot as { name: string; legal_name?: string | null; tax_number?: string | null; address?: string | null; phone?: string | null; email?: string | null; tax?: { label?: string | null } };
  const buyer = inv.buyer_snapshot as { name?: string };
  const ar = locale === 'ar';
  const L = ar
    ? { receipt: 'إيصال دفع', invoice: 'فاتورة', credit_note: 'إشعار دائن', no: 'رقم', date: 'التاريخ', to: 'إلى', item: 'البيان', qty: 'الكمية', amount: 'المبلغ', subtotal: 'المجموع', discount: 'الخصم', tax: seller.tax?.label || 'الضريبة', total: 'الإجمالي', taxNo: 'الرقم الضريبي', note: 'مستند صادر من نظام لوما. لا يُدّعى الامتثال لمتطلبات الفوترة الإلكترونية.' }
    : { receipt: 'Payment receipt', invoice: 'Invoice', credit_note: 'Credit note', no: 'No.', date: 'Date', to: 'To', item: 'Description', qty: 'Qty', amount: 'Amount', subtotal: 'Subtotal', discount: 'Discount', tax: seller.tax?.label || 'Tax', total: 'Total', taxNo: 'Tax number', note: 'Document generated by LUMA. No e-invoicing compliance is claimed.' };
  const m = (v: number) => e(formatMoney(v, inv.currency, locale));
  return `<!doctype html><html lang="${locale}" dir="${ar ? 'rtl' : 'ltr'}"><head><meta charset="utf-8"><title>${e(inv.number)}</title>
<style>
  body{font-family:"Noto Naskh Arabic","Noto Sans Arabic","DejaVu Sans",Arial,sans-serif;color:#222;margin:0;padding:24px;font-size:13px}
  h1{font-size:20px;margin:0 0 4px} .muted{color:#666} table{width:100%;border-collapse:collapse;margin-top:16px}
  th,td{padding:8px;border-bottom:1px solid #ddd;text-align:start} th{background:#f6f6f6} .num{text-align:end;white-space:nowrap}
  .head{display:flex;justify-content:space-between;gap:16px} .totals{margin-top:12px;width:280px;margin-inline-start:auto}
  .totals div{display:flex;justify-content:space-between;padding:4px 0} .grand{font-weight:bold;border-top:2px solid #222}
  footer{margin-top:32px;font-size:11px;color:#777}
</style></head><body>
<div class="head"><div><h1>${e(seller.legal_name || seller.name)}</h1>
<div class="muted">${e(seller.address)}</div><div class="muted">${e(seller.phone)} ${e(seller.email)}</div>
${seller.tax_number ? `<div>${L.taxNo}: <span dir="ltr">${e(seller.tax_number)}</span></div>` : ''}</div>
<div><h1>${L[inv.kind as 'receipt' | 'invoice' | 'credit_note']}</h1><div>${L.no}: <span dir="ltr">${e(inv.number)}</span></div>
<div>${L.date}: ${e(formatDateTime(inv.issued_at, { tz: inv.tenant.timezone, locale }))}</div>${buyer.name ? `<div>${L.to}: ${e(buyer.name)}</div>` : ''}</div></div>
<table><thead><tr><th>${L.item}</th><th class="num">${L.qty}</th><th class="num">${L.amount}</th></tr></thead><tbody>
${inv.items.map((i) => `<tr><td>${e(i.description)}</td><td class="num">${e(i.quantity)}</td><td class="num">${m(i.line_total_minor)}</td></tr>`).join('')}
</tbody></table>
<div class="totals"><div><span>${L.subtotal}</span><span>${m(inv.subtotal_minor)}</span></div>
${inv.discount_minor ? `<div><span>${L.discount}</span><span>${m(inv.discount_minor)}</span></div>` : ''}
${inv.tax_minor ? `<div><span>${L.tax}</span><span>${m(inv.tax_minor)}</span></div>` : ''}
<div class="grand"><span>${L.total}</span><span>${m(inv.total_minor)}</span></div></div>
<footer>${L.note} · Powered by LUMA</footer></body></html>`;
}

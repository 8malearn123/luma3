import { escapeHtml as e } from '../../infra/pdf';
import { formatDateTime, formatMoney } from '@/shared/format';

type Slip = Awaited<ReturnType<typeof import('./service').getSlip>>;
type Line = { kind: 'bonus' | 'deduction' | 'advance' | 'tip'; amount_minor: number; effective_on: string; note: string | null; installment?: { index: number; of: number } };

/** Self-contained printable payslip (RTL in Arabic). */
export function payslipHtml(s: Slip, locale: 'ar' | 'en' = 'ar') {
  const ar = locale === 'ar';
  const L = ar
    ? { title: 'قسيمة راتب', no: 'رقم', month: 'الشهر', employee: 'الموظفة', item: 'البند', amount: 'المبلغ', base: 'الراتب الأساسي', days: 'يوم عمل من', of: 'من',
      services: 'عمولة الخدمات', products: 'عمولة المنتجات', sales: 'مبيعات', rate: 'بنسبة', tips: 'البقشيش', bonus: 'مكافآت', deduction: 'خصومات', advance: 'أقساط السلف',
      net: 'صافي المستحق', paid: 'تم الصرف', unpaid: 'لم يُصرف بعد', details: 'تفاصيل الحركات', closed: 'أُقفل في', installment: 'قسط',
      methods: { cash: 'نقداً', bank_transfer: 'تحويل بنكي' }, kinds: { bonus: 'مكافأة', deduction: 'خصم', advance: 'سلفة', tip: 'بقشيش' }, note: 'مستند صادر من لوما.' }
    : { title: 'Payslip', no: 'No.', month: 'Month', employee: 'Employee', item: 'Item', amount: 'Amount', base: 'Base salary', days: 'days worked of', of: 'of',
      services: 'Service commission', products: 'Product commission', sales: 'sales', rate: 'at', tips: 'Tips', bonus: 'Bonuses', deduction: 'Deductions', advance: 'Advance instalments',
      net: 'Net pay', paid: 'Paid', unpaid: 'Not paid yet', details: 'Entries', closed: 'Closed on', installment: 'instalment',
      methods: { cash: 'cash', bank_transfer: 'bank transfer' }, kinds: { bonus: 'Bonus', deduction: 'Deduction', advance: 'Advance', tip: 'Tip' }, note: 'Document generated by LUMA.' };
  const m = (v: number) => e(formatMoney(v, s.currency, locale));
  const neg = (v: number) => (v ? m(-v) : m(0));
  const pct = (bp: number) => `${Number((bp / 100).toFixed(2))}%`;
  const lines = (s.lines as Line[] | null) ?? [];
  const rows: Array<[string, string]> = [
    [s.days_employed < s.days_in_month ? `${L.base} (${s.days_employed} ${L.days} ${s.days_in_month} — ${m(s.base_full_minor)})` : L.base, m(s.base_minor)],
    [`${L.services} (${L.sales} ${m(s.service_sales_minor)} ${L.rate} ${pct(s.service_rate_bp)})`, m(s.service_commission_minor)],
    ...(s.product_sales_minor || s.product_commission_minor ? [[`${L.products} (${L.sales} ${m(s.product_sales_minor)} ${L.rate} ${pct(s.product_rate_bp)})`, m(s.product_commission_minor)] as [string, string]] : []),
    [L.tips, m(s.tips_minor)],
    [L.bonus, m(s.bonus_minor)],
    [L.deduction, neg(s.deduction_minor)],
    [L.advance, neg(s.advance_minor)],
  ];
  const paid = s.paid_at ? `${L.paid} · ${e(formatDateTime(s.paid_at, { tz: s.timezone, locale }))}${s.paid_method ? ` · ${L.methods[s.paid_method as 'cash' | 'bank_transfer']}` : ''}` : L.unpaid;
  return `<!doctype html><html lang="${locale}" dir="${ar ? 'rtl' : 'ltr'}"><head><meta charset="utf-8"><title>${e(s.number)}</title>
<style>
  body{font-family:"Noto Naskh Arabic","Noto Sans Arabic","DejaVu Sans",Arial,sans-serif;color:#222;margin:0;padding:24px;font-size:13px}
  h1{font-size:20px;margin:0 0 4px} h2{font-size:14px;margin:24px 0 0} .muted{color:#666} table{width:100%;border-collapse:collapse;margin-top:12px}
  th,td{padding:8px;border-bottom:1px solid #ddd;text-align:start} th{background:#f6f6f6} .num{text-align:end;white-space:nowrap}
  .head{display:flex;justify-content:space-between;gap:16px} .grand td{font-weight:bold;border-top:2px solid #222;font-size:15px}
  .badge{display:inline-block;padding:2px 8px;border-radius:99px;font-size:11px;background:#eee} .ok{background:#e3f4e8;color:#1d6b3a}
  footer{margin-top:32px;font-size:11px;color:#777}
</style></head><body>
<div class="head"><div><h1>${e(s.employer.name)}</h1><div class="muted">${e(s.employer.address)}</div><div class="muted">${e(s.employer.phone)}</div></div>
<div><h1>${L.title}</h1><div>${L.no}: <span dir="ltr">${e(s.number)}</span></div><div>${L.month}: <span dir="ltr">${e(s.month)}</span></div>
<div>${L.employee}: ${e(s.staff_name)}</div>
<div class="muted">${L.closed} ${e(formatDateTime(s.closed_at, { tz: s.timezone, locale }))}</div>
<div><span class="badge ${s.paid_at ? 'ok' : ''}">${paid}</span></div></div></div>
<table><thead><tr><th>${L.item}</th><th class="num">${L.amount}</th></tr></thead><tbody>
${rows.map(([k, v]) => `<tr><td>${k}</td><td class="num">${v}</td></tr>`).join('')}
<tr class="grand"><td>${L.net}</td><td class="num">${m(s.net_minor)}</td></tr>
</tbody></table>
${lines.length ? `<h2>${L.details}</h2><table><tbody>${lines.map((l) => `<tr><td dir="ltr" class="muted">${e(l.effective_on)}</td><td>${e(L.kinds[l.kind])}${l.installment ? ` · ${L.installment} ${l.installment.index} ${L.of} ${l.installment.of}` : ''}${l.note ? ` · ${e(l.note)}` : ''}</td><td class="num">${l.kind === 'deduction' || l.kind === 'advance' ? m(-l.amount_minor) : m(l.amount_minor)}</td></tr>`).join('')}</tbody></table>` : ''}
<footer>${L.note} · Powered by LUMA</footer></body></html>`;
}
